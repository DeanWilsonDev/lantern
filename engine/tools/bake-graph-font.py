#!/usr/bin/env python3
# Bakes the Graph tab's text: Actor at four pixel sizes (one per zoom level) as 4-bit coverage, written as Nox source.
# Run: python3 engine/tools/bake-graph-font.py > engine/src/graph-canvas/GraphFontData.nox
import sys
from PIL import Image, ImageDraw, ImageFont

FONT_PATH = "apps/world-editor/data/fonts/Actor-Regular.ttf"
SIZES = [10, 14, 20, 26]
FIRST, LAST = 32, 126

def bake(size):
    font = ImageFont.truetype(FONT_PATH, size)
    ascent, _descent = font.getmetrics()
    metrics = []
    alpha = []
    for code in range(FIRST, LAST + 1):
        character = chr(code)
        advance16 = round(font.getlength(character) * 16)
        left, top, right, bottom = font.getbbox(character, anchor="ls")
        width, height = right - left, bottom - top
        offset = len("".join(alpha))
        if width > 0 and height > 0:
            picture = Image.new("L", (width, height), 0)
            ImageDraw.Draw(picture).text((-left, -top), character, font=font, fill=255, anchor="ls")
            for value in picture.getdata():
                alpha.append("%x" % ((value + 8) // 17))
        else:
            width = height = 0
        metrics.extend([advance16, width, height, left, top, offset])
    return ascent, metrics, "".join(alpha)

out = []
out.append("// Generated by engine/tools/bake-graph-font.py from Actor (SIL OFL 1.1, see apps/world-editor/data/fonts/Actor-LICENSE.txt). Do not edit.")
out.append("// Four pixel sizes, one per graph zoom. Each glyph is six numbers: advance in sixteenths of a pixel, width, height, left bearing,")
out.append("// top (negative, above the baseline) and where its coverage starts in the size's text. Coverage is one hex digit per pixel, 0 to f.")
out.append("lantern:::graphs :: namespace {")
out.append("    GRAPH_FONT_SIZES: i32 : %d;" % len(SIZES))
out.append("    GRAPH_FONT_FIRST: i32 : %d;" % FIRST)
out.append("    GRAPH_FONT_FIELDS: usize : 6;")
out.append("")
asc = []
for index, size in enumerate(SIZES):
    ascent, metrics, alpha = bake(size)
    asc.append((size, ascent))
    out.append("    GraphFontMetrics%d :: () -> Array<i32>! {" % index)
    out.append("        list~ Array<i32>! = [];")
    for value in metrics:
        out.append("        list.push(%d);" % value)
    out.append("        return list!;")
    out.append("    }")
    out.append("")
    out.append("    GraphFontCoverage%d :: () -> string {" % index)
    out.append('        return "%s";' % alpha)
    out.append("    }")
    out.append("")
out.append("    GraphFontPixelSize :: (sizeIndex: i32) -> i32 {")
for index, (size, _) in enumerate(asc):
    out.append("        if sizeIndex == %d {\n            return %d;\n        }" % (index, size))
out.append("        return %d;\n    }" % asc[-1][0])
out.append("")
out.append("    GraphFontAscent :: (sizeIndex: i32) -> i32 {")
for index, (_, ascent) in enumerate(asc):
    out.append("        if sizeIndex == %d {\n            return %d;\n        }" % (index, ascent))
out.append("        return %d;\n    }" % asc[-1][1])
out.append("")
out.append("    GraphFontMetrics :: (sizeIndex: i32) -> Array<i32>! {")
for index in range(len(SIZES) - 1):
    out.append("        if sizeIndex == %d {\n            return GraphFontMetrics%d();\n        }" % (index, index))
out.append("        return GraphFontMetrics%d();\n    }" % (len(SIZES) - 1))
out.append("")
out.append("    GraphFontCoverage :: (sizeIndex: i32) -> string {")
for index in range(len(SIZES) - 1):
    out.append("        if sizeIndex == %d {\n            return GraphFontCoverage%d();\n        }" % (index, index))
out.append("        return GraphFontCoverage%d();\n    }" % (len(SIZES) - 1))
out.append("}")
sys.stdout.write("\n".join(out) + "\n")
