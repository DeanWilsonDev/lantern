//! Compiles `shaders/*.wgsl` to SPIR-V (Vulkan) and MSL (Metal) with naga (decision D-004) and
//! writes `shader_manifest.rs`, which says for each entry point how many samplers and uniform
//! buffers SDL must be told about.
//!
//! Binding convention, mapped onto SDL GPU's required layout:
//!
//! | WGSL                  | meaning                     | SPIR-V            | MSL                 |
//! |-----------------------|-----------------------------|-------------------|---------------------|
//! | group 1, binding b    | vertex uniform buffer b     | set 1, binding b  | `[[buffer(b)]]`     |
//! | group 3, binding b    | fragment uniform buffer b   | set 3, binding b  | `[[buffer(b)]]`     |
//! | group 2, binding 2k   | fragment texture k          | set 2, binding k  | `[[texture(k)]]`    |
//! | group 2, binding 2k+1 | fragment sampler k          | set 2, binding k  | `[[sampler(k)]]`    |
//!
//! A texture and its sampler share one SPIR-V binding because SDL creates a combined
//! image-sampler descriptor there, which Vulkan lets separate image and sampler variables use.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use naga::back::{msl, spv};
use naga::{AddressSpace, ShaderStage};

const SHADERS: [&str; 3] = ["lit", "lines", "overlay"];
const ENTRY_POINTS: [(ShaderStage, &str); 2] =
    [(ShaderStage::Vertex, "vertex_main"), (ShaderStage::Fragment, "fragment_main")];

struct ResourceCounts {
    samplers: u32,
    uniform_buffers: u32,
}

fn main() {
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"));
    let shader_dir = manifest_dir.join("../../shaders");
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets OUT_DIR"));
    let mut manifest = String::from("// Generated by build.rs from shaders/*.wgsl. Do not edit.\n\n");
    for name in SHADERS {
        compile_shader(&shader_dir.join(format!("{name}.wgsl")), name, &out_dir, &mut manifest);
    }
    std::fs::write(out_dir.join("shader_manifest.rs"), manifest).expect("can write the shader manifest");
}

fn fail(path: &Path, message: impl std::fmt::Display) -> ! {
    panic!("shader {}: {message}", path.display());
}

fn compile_shader(path: &Path, name: &str, out_dir: &Path, manifest: &mut String) {
    println!("cargo:rerun-if-changed={}", path.display());
    let source = std::fs::read_to_string(path).unwrap_or_else(|error| fail(path, error));
    let module =
        naga::front::wgsl::parse_str(&source).unwrap_or_else(|error| fail(path, error.emit_to_string(&source)));
    let info = naga::valid::Validator::new(naga::valid::ValidationFlags::all(), naga::valid::Capabilities::empty())
        .validate(&module)
        .unwrap_or_else(|error| fail(path, error.emit_to_string(&source)));

    // SPIR-V, one module per entry point.
    let mut spirv_options = spv::Options {
        binding_map: spirv_binding_map(&module, path),
        fake_missing_bindings: false,
        ..Default::default()
    };
    // SDL GPU already gives every backend the same clip space (y up, depth 0..1).
    spirv_options.flags.remove(spv::WriterFlags::ADJUST_COORDINATE_SPACE);
    for (stage, entry_point) in ENTRY_POINTS {
        let pipeline = spv::PipelineOptions { shader_stage: stage, entry_point: entry_point.to_string() };
        let words =
            spv::write_vec(&module, &info, &spirv_options, Some(&pipeline)).unwrap_or_else(|error| fail(path, error));
        let bytes: Vec<u8> = words.iter().flat_map(|word| word.to_le_bytes()).collect();
        std::fs::write(out_dir.join(format!("{name}.{entry_point}.spv")), bytes).expect("can write SPIR-V");
    }

    // MSL, one source for both entry points.
    let msl_options = msl::Options {
        lang_version: (2, 1),
        per_entry_point_map: msl_resource_map(&module),
        fake_missing_bindings: false,
        ..Default::default()
    };
    let (msl_source, translation) = msl::write_string(&module, &info, &msl_options, &msl::PipelineOptions::default())
        .unwrap_or_else(|error| fail(path, error));
    std::fs::write(out_dir.join(format!("{name}.metal")), &msl_source).expect("can write MSL");

    // Manifest entries.
    for (entry_index, entry) in module.entry_points.iter().enumerate() {
        let counts = resource_counts(&module, info.get_entry_point(entry_index), entry.stage);
        let msl_name = translation.entry_point_names[entry_index]
            .as_ref()
            .unwrap_or_else(|error| fail(path, format!("{error:?}")));
        let constant = format!(
            "{}_{}",
            name.to_uppercase(),
            if entry.stage == ShaderStage::Vertex { "VERTEX" } else { "FRAGMENT" }
        );
        writeln!(
            manifest,
            "pub const {constant}: CompiledShader = CompiledShader {{\n    name: \"{name}.{entry}\",\n    spirv: include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{name}.{entry}.spv\")),\n    msl: include_str!(concat!(env!(\"OUT_DIR\"), \"/{name}.metal\")),\n    entry_point: \"{entry}\",\n    msl_entry_point: \"{msl_name}\",\n    stage: ShaderStageKind::{stage:?},\n    sampler_count: {samplers},\n    uniform_buffer_count: {uniforms},\n}};",
            entry = entry.name,
            stage = entry.stage,
            samplers = counts.samplers,
            uniforms = counts.uniform_buffers,
        )
        .expect("writing to a String cannot fail");
    }
}

fn spirv_binding_map(module: &naga::Module, path: &Path) -> spv::BindingMap {
    let mut map = spv::BindingMap::default();
    for (_, variable) in module.global_variables.iter() {
        let Some(binding) = variable.binding else { continue };
        let target = match binding.group {
            1 | 3 => binding.binding,
            0 | 2 => binding.binding / 2,
            group => fail(path, format!("binding group {group} is not part of SDL GPU's layout")),
        };
        map.insert(
            binding,
            spv::BindingInfo { descriptor_set: binding.group, binding: target, binding_array_size: None },
        );
    }
    map
}

fn msl_resource_map(module: &naga::Module) -> msl::EntryPointResourceMap {
    let mut per_entry_point = BTreeMap::new();
    for entry in &module.entry_points {
        let mut resources = BTreeMap::new();
        for (_, variable) in module.global_variables.iter() {
            let Some(binding) = variable.binding else { continue };
            let slot = binding.binding;
            let target = match (binding.group, variable.space) {
                (1 | 3, AddressSpace::Uniform) => msl::BindTarget { buffer: Some(slot as u8), ..Default::default() },
                (0 | 2, _) if slot % 2 == 0 => {
                    msl::BindTarget { texture: Some((slot / 2) as u8), ..Default::default() }
                }
                (0 | 2, _) => msl::BindTarget {
                    sampler: Some(msl::BindSamplerTarget::Resource((slot / 2) as u8)),
                    ..Default::default()
                },
                _ => continue,
            };
            resources.insert(binding, target);
        }
        per_entry_point.insert(entry.name.clone(), msl::EntryPointResources { resources, ..Default::default() });
    }
    per_entry_point
}

fn resource_counts(module: &naga::Module, info: &naga::valid::FunctionInfo, stage: ShaderStage) -> ResourceCounts {
    let mut counts = ResourceCounts { samplers: 0, uniform_buffers: 0 };
    let (uniform_group, texture_group) = if stage == ShaderStage::Vertex { (1, 0) } else { (3, 2) };
    for (handle, variable) in module.global_variables.iter() {
        let Some(binding) = variable.binding else { continue };
        if info[handle].is_empty() {
            continue; // not used by this entry point
        }
        if binding.group == uniform_group && variable.space == AddressSpace::Uniform {
            counts.uniform_buffers = counts.uniform_buffers.max(binding.binding + 1);
        }
        if binding.group == texture_group && binding.binding % 2 == 0 {
            counts.samplers = counts.samplers.max(binding.binding / 2 + 1);
        }
    }
    counts
}
